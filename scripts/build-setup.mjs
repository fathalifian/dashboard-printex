import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
// Bundles every migration into one reviewable file for an empty public schema.
// Never connects to a database. --check fails when the bundle is out of date.
const names = readdirSync('supabase/migrations').filter(name => name.endsWith('.sql')).sort()
const body = names.map(name => '-- supabase/migrations/' + name + '\n' + readFileSync('supabase/migrations/' + name, 'utf8')
  .replace(/\r\n/g, '\n').replace(/^BEGIN;\s*$/gm, '').replace(/^COMMIT;\s*$/gm, '')).join('\n')
const output = `-- Generated by npm run db:setup from supabase/migrations (${names[0].slice(0, 4)}–${names.at(-1).slice(0, 4)}). Do not edit by hand.
-- Builds the complete Printex database (one production location) in an EMPTY public schema.
-- For the existing project, run supabase/manual/1_SIMPAN_DAN_KOSONGKAN.sql first (see supabase/manual/README.md).
BEGIN;
DO $$ BEGIN
 IF to_regclass('public.orders') IS NOT NULL THEN
  RAISE EXCEPTION 'Database sudah berisi tabel Printex. Jalankan supabase/manual/1_SIMPAN_DAN_KOSONGKAN.sql terlebih dahulu.';
 END IF;
END $$;
${body}
COMMIT;
`
if (process.argv.includes('--check')) {
  if (readFileSync('supabase/SETUP.sql', 'utf8').replace(/\r\n/g, '\n') !== output) throw new Error('SETUP.sql belum diperbarui. Jalankan npm run db:setup.')
  console.log('SETUP.sql matches its source migrations.')
} else {
  writeFileSync('supabase/SETUP.sql', output)
  console.log('Generated supabase/SETUP.sql. Review and run it in the Supabase SQL Editor. No database was modified.')
}
