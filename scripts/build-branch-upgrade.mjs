import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
// Generates a reviewable, atomic upgrade. Never connects to a live database.
const branch = process.argv[2]
if (!['Salatiga', 'Semarang', '--existing'].includes(branch)) {
  throw new Error('Gunakan: npm run db:branch-upgrade -- Salatiga | Semarang | --existing. Pilih cabang pemilik data lama; --existing hanya untuk cabang yang sudah aktif.')
}
const names = readdirSync('supabase/branch-migrations').filter(name => name.endsWith('.sql')).sort()
const files = ['supabase/migrations/0021_incremental_sync.sql', ...names.map(name => 'supabase/branch-migrations/' + name)]
const body = files.map(file => '-- ' + file + '\n' + readFileSync(file, 'utf8').replace(/\r\n/g, '\n').replace(/^BEGIN;\s*$/gm, '').replace(/^COMMIT;\s*$/gm, '')).join('\n')
const preflight = branch === '--existing'
  ? `DO $$ BEGIN IF to_regclass('public.branches') IS NULL THEN RAISE EXCEPTION 'Database belum memiliki cabang. Pilih cabang pemilik data lama.'; END IF; END $$;`
  : `SET LOCAL printex.legacy_branch = '${branch}';`
const output = '-- Generated by npm run db:branch-upgrade. Requires base migrations 0001-0020.\nBEGIN;\n' + preflight + '\n' + body + '\nCOMMIT;\n'
if (process.argv.includes('--check')) {
  if (readFileSync('supabase/UPGRADE_BRANCHES.sql','utf8').replace(/\r\n/g, '\n') !== output) throw new Error('Paket SQL belum diperbarui. Jalankan npm run db:branch-upgrade -- --existing.')
} else writeFileSync('supabase/UPGRADE_BRANCHES.sql', output)
console.log(process.argv.includes('--check') ? 'Branch SQL bundle matches its source migrations.' : 'Generated supabase/UPGRADE_BRANCHES.sql. Review and run once in Supabase SQL Editor. No database was modified.')
